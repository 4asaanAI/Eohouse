function addVariablesForColors({ addBase }: any) {
  let allColors = flattenColorPalette(colors);
  let newVars = Object.fromEntries(
    Object.entries(allColors).map(([key, val]) => [`--${key}`, val])
  );

  addBase({
    ":root": newVars,
  });
}
